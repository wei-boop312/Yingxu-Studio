import {readFileSync,mkdirSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const commerce=fileURLToPath(new URL('../../../',import.meta.url));
const python=path.join(commerce,process.platform==='win32'?'.venv/Scripts/python.exe':'.venv/bin/python');
const fixture=path.join(commerce,'tests/fixtures/studio/synthetic-sku-a.png');
