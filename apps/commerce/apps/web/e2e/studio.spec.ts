 await expect(dialog).toBeVisible();await dialog.getByLabel('项目名称').fill('合成样例 · DE 十图验收');
 await choose('目标平台','amazon');
 await dialog.getByLabel('目标市场').fill('DE');await dialog.getByLabel('内容语言').fill('de');
 await dialog.getByLabel('目标类目').fill('generic');
 await dialog.getByLabel('宽度像素').fill('1600');await dialog.getByLabel('高度像素').fill('1600');
