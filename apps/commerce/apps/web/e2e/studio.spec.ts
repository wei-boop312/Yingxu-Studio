 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 const choose=async(name:string,text:string)=>{const combo=page.getByRole('combobox',{name,exact:true});await combo.click();const id=await combo.getAttribute('aria-controls');await page.locator('[id="'+id+'"]').getByRole('option',{name:text,exact:true}).click();await combo.blur();await expect(combo).toHaveAttribute('aria-expanded','false')};
 await page.goto('/#suites');
 await page.getByLabel('邮箱',{exact:true}).fill(account.email);
 await page.getByLabel('密码',{exact:true}).fill(account.password);
